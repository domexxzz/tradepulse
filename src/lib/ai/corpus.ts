/** ราคาปัจจุบัน — สร้างจาก config + ที่นั่งโปรที่เหลือจริง ไม่มีวันเก่ากว่าหน้าเว็บ */
function pricingDoc(promo: PromoState): KnowledgeDoc {
  const list = plansFor(promo.monthlyTHB)
    .map((p) => `${p.name} ${p.priceTHB.toLocaleString("en-US")} บาท (เฉลี่ย ${p.perMonthTHB.toLocaleString("en-US")}/เดือน)`)
    .join(" · ");
  const promoLine = promo.active
    ? `ตอนนี้เป็นโปร Founding ${PROMO_SEATS} ที่นั่งแรก เหลือ ${promo.remaining} ที่นั่ง — คนที่ได้ราคาโปรจะถูกล็อกราคานี้ไว้ตราบที่ต่ออายุต่อเนื่อง`
    : `โปร Founding ${PROMO_SEATS} ที่นั่งเต็มแล้ว ตอนนี้เป็นราคาปกติ (สมาชิกที่ล็อกราคาโปรไว้และต่ออายุต่อเนื่องยังได้ราคาเดิม)`;
  return {
    id: "pricing",
    title: "ราคาแพ็กเกจสมาชิก QVX (ราคา ค่าสมาชิก เท่าไหร่)",
    text: `${promoLine}
ราคาแพ็กเกจ: ${list}
แพ็กเกจรวม: ${planIncludes.join(" · ")}
ชำระผ่าน QR พร้อมเพย์แล้วแนบสลิปในหน้าชำระเงิน · อีกทางไม่ต้องจ่ายค่าสมาชิกคือเปิดบัญชีโบรก Wisdom ผ่านลิงก์ของ QVX · ราคาที่หน้าชำระเงินคือราคาที่ถูกต้องที่สุดสำหรับบัญชีนั้น`,
  };
}

