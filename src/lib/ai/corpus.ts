function faqDocs(): KnowledgeDoc[] {
  return faqs.map((f, i) => ({ id: `faq-${i}`, title: `FAQ: ${f.q}`, text: f.a }));
}

export function staticDocs(): KnowledgeDoc[] {
  return [...STATIC_DOCS, wisdomDoc(), ...faqDocs()];
}

